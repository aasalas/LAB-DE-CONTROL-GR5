% Prepara PiL.slx: el bloque MATLAB Function llama a pil_ctrl cada 10 ms.
mdl = 'PiL';
load_system(mdl);
rt = sfroot;
m  = rt.find('-isa', 'Simulink.BlockDiagram', 'Name', mdl);
ch = m.find('-isa', 'Stateflow.EMChart', 'Path', [mdl '/MATLAB Function']);
ch.Script = sprintf(['function u = pi_inc(ref, x)\n' ...
    '%% Controlador PI: MiL (MATLAB) o PiL (Arduino por UART), ver pil_ctrl.m\n' ...
    'coder.extrinsic(''pil_ctrl'');\n' ...
    'u = 0;\n' ...
    'u = pil_ctrl(ref, x);\n' ...
    'end\n']);
set_param(mdl, 'StopTime', '4');
save_system(mdl);
disp('pil_setup OK');
